for texture in blocks_list:
    with Image.open(f"assets\\block_textures\\{texture}.png") as img:
        nparray = np.asarray(img.convert("RGB").transpose(Image.FLIP_TOP_BOTTOM).resize((64, 64)))
        array = []
        for row in nparray:
            for px in row: array.append((int(px[0]), int(px[1]), int(px[2])))
        result = (0, 0, 0)
        for px in array: result = (result[0] + px[0], result[1] + px[1], result[2] + px[2])
        result = (result[0] / len(array), result[1] / len(array), result[2] / len(array))
        print(f"    ({result[0]}, {result[1]}, {result[2]}),")
