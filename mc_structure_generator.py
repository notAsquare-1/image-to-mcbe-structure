def select_image():
    global selected_image_display, image_path_entry, result_image_display, avg_error, image_loaded, file_path
    file_path = Path(ctk.filedialog.askopenfilename(title="Select an image to use", filetypes=[("PNG files", "*.png"), ("JPG files", "*.jpg")]))
    try:
        selected_image = Image.open(file_path)
        image_loaded = True
        selected_image_display.configure(image=ctk.CTkImage(Image.open(file_path), size=(300, 300)))
        image_path_entry.delete(0, "end")
        image_path_entry.insert(0, file_path)
        nparray = np.asarray(selected_image.convert("RGB").transpose(Image.FLIP_TOP_BOTTOM).resize((64, 64)))
        array = []
        for row in nparray:
            for px in row: array.append((int(px[0]), int(px[1]), int(px[2])))
        block_list = []
        colors_list = []
        avg_error = 0
        for px in array:
            best = (0, 99999)
            best_col = (255, 255, 255)
            for block_id, col in enumerate(colors):
                score = float(math.dist(col, px))
                if score < best[1]: 
                    best = (block_id, score)
                    best_col = col
            block_list.append(best[0])
            colors_list.append((round(best_col[0]), round(best_col[1]), round(best_col[2])))
            avg_error += best[1]
        avg_error /= len(array)
        structure["value"]["structure"]["value"]["block_indices"]["value"]["value"][0]["value"] = block_list
        result_img = Image.new("RGB", size=(64, 64))
        result_img.putdata(colors_list)
        result_img.resize((300, 300))
        result_image_display.configure(image=ctk.CTkImage(result_img.transpose(Image.FLIP_TOP_BOTTOM), size=(300, 300)))
        error_label.configure(text=f"Average Error: {avg_error}")
    except Exception as e: print(e)
def save_as_json(): 
    global image_loaded, app_root
    def reset(): error_label.configure(text=f"Average Error: {avg_error}")
    try:
        if image_loaded:
            with open(f"saved_structures\\{file_path.stem}.json", "w") as out_file: 
                out_file.write(json.dumps(structure))
                error_label.configure(text=f"Successfully saved structure to saved_structures/{file_path.stem}.json")
        else: error_label.configure(text="No image loaded")
    except Exception as e:
        error_label.configure(text="Failed to save, check terminal for more details")
        print(e)
    finally: app_root.after(3000, reset)

